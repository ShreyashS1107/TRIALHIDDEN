def test_custom_project_result_page():
    print("\n--- 3. Testing GET /custom-project/result (SSR and Visual Components) ---")
    url = "http://localhost:3000/custom-project/result"
    req = urllib.request.Request(url, headers={'User-Agent': 'PAIMANA-Test'})
    with urllib.request.urlopen(req, timeout=10) as res:
        assert res.status == 200, f"Expected status 200, got {res.status}"
        html = res.read().decode('utf-8')

        # Check required labels and sections matching Step 6 audited specification
        required_substrings = [
            "OVERALL INTEGRATED RISK",
            "Schedule Delay Risk",
            "Cost Overrun Risk",
            "Schedule Revision Risk",
            "COST ANALYSIS",
            "DELIVERY SCHEDULE INTELLIGENCE",
            "MODEL-DERIVED RISK SIGNALS",
            "DECISION-SUPPORT LAYER",
            "MODEL TRANSPARENCY",
            "PHYSICAL VS FINANCIAL CONVERGENCE",
            "Prediction identifies risk; intervention recommendations are generated by the decision-support layer.",
            "MODEL-DERIVED SIGNAL",
            "OBSERVED PROJECT METRIC",
            "DECISION-SUPPORT INTERPRETATION",
            "SIMULATE ANOTHER SCENARIO",
            "ASSESS ANOTHER PROJECT",
            "RETURN TO COMMAND CENTER",
        ]

        missing = []
        for text in required_substrings:
            if text not in html:
                missing.append(text)

        if missing:
            print(f"  [FAIL] Missing elements in rendered HTML: {missing}")
            sys.exit(1)

        print("  [PASS] All 11 required Step 6 sections, badges, CTAs, signals, and disclaimers are present in HTML.")

