import urllib.request
import json
import sys

def test_fastapi_health_and_confidence():
    print("\n--- 1. Testing FastAPI /health and /predict/project confidence & intervention ---")
    url = "http://127.0.0.1:8000/predict/project"
    payload = {
        "project_name": "Bengaluru High-Speed Airport Metro Link",
        "project_id": "BMRCL-AIRPORT-LINK-01",
        "agency": "Ministry of Railways [MOR]",
        "state": "Karnataka",
        "original_cost_crore": 5600.0,
        "revised_cost_crore": 6450.0,
        "approval_start_date": "2023-01",
        "original_completion_date": "2026-12",
        "revised_completion_date": "2027-09",
        "physical_progress_percent": 34.0,
        "is_completed": False,
        "cumulative_expenditure_crore": 2200.0
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode('utf-8'),
        headers={'Content-Type': 'application/json', 'User-Agent': 'PAIMANA-Test'},
        method='POST'
    )
    with urllib.request.urlopen(req, timeout=10) as res:
        assert res.status == 200, f"Expected status 200, got {res.status}"
        data = json.loads(res.read().decode('utf-8'))
        print(f"  Project: {data['project_name']}")
        print(f"  Risk Band: {data['risk_band']}")
        print(f"  Model Confidence: {data.get('model_confidence')}")
        print(f"  Intervention: {data.get('recommended_intervention')[:60]}...")
        assert "model_confidence" in data and data["model_confidence"] is not None, "Missing model_confidence"
        assert "recommended_intervention" in data and len(data["recommended_intervention"]) > 0, "Missing intervention"
        assert data.get("original_cost_crore") == 5600.0, "Original cost not echoed"
        print("  [PASS] FastAPI ML microservice outputs confidence and prescriptive intervention.")

